"""CCV eBUS XML INVOIC (<INVOIC><HDR>…</HDR><LIN>…) -> ORION XML 3.

Uses the production converter "INVOIC exp ORION 3 XML" (copy generated by tools/import_ccv_xsl.py,
without the database extensions and the ORION URL)."""
from __future__ import annotations

from lxml import etree

from ..resources import data_path
from ..xmlval import saxon

XSL = "ccv_xml_to_orion3.xsl"


def to_orion3(data: bytes) -> bytes:
    text = data.decode("utf-8-sig") if not data.lstrip().startswith(b"<?xml") or b"utf-8" in data[:100].lower() \
        else data.decode("cp1250")
    with saxon.LOCK:
        exe = saxon.stylesheet(str(data_path("orion", XSL)))
        out = exe.transform_to_string(xdm_node=saxon.parse(text))
    if not out or "<orion_message" not in out:
        raise ValueError("převodník nevrátil ORION XML")
    return out.encode("utf-8")
