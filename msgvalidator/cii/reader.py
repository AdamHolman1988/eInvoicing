"""UN/CEFACT CII (CrossIndustryInvoice D16B) -> semantic model (EN 16931 BTs).

Driven by the CII syntax binding data/peppol/cii_binding.json (generated by tools/build_cii_binding.py from the
KoSIT XRechnung visualization). Same output as the UBL reader, so gap analysis, profiles and value checks run
on CII (and on ZUGFeRD / Factur-X PDFs, which embed CII) exactly like on any other format.
"""
from __future__ import annotations

import datetime as dt
import json
import re
from functools import lru_cache

from lxml import etree

from ..resources import data_path
from ..semantic.catalog import catalog, codelists
from ..semantic.model import Context, Semantic, Value

ROOT = "/rsm:CrossIndustryInvoice"
HS = ROOT + "/rsm:SupplyChainTradeTransaction/ram:ApplicableHeaderTradeSettlement"
LINE = ROOT + "/rsm:SupplyChainTradeTransaction/ram:IncludedSupplyChainTradeLineItem"
REPEATING = ("BG-20", "BG-21", "BG-23", "BG-25")
LINE_SUB = ("BG-27", "BG-28")
# terms the visualization fills inline (no template of their own)
EXTRA = {
    "BT-7": [HS + "/ram:ApplicableTradeTax/ram:TaxPointDate/udt:DateString"],
    "BT-149": [LINE + "/ram:SpecifiedLineTradeAgreement/ram:NetPriceProductTradePrice/ram:BasisQuantity/@unitCode"],
}


@lru_cache(maxsize=1)
def binding() -> dict:
    b = json.loads(data_path("peppol", "cii_binding.json").read_text(encoding="utf-8"))
    for bt, paths in EXTRA.items():
        b["terms"].setdefault(bt, paths)
    return b


def _plain(xp: str) -> str:
    """Path without predicates – to test whether a term lies inside a group."""
    out, depth = [], 0
    for ch in xp:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        elif depth == 0:
            out.append(ch)
    return "".join(out)


def _relative(term: str, base: str) -> str | None:
    """term path relative to the group base (predicates of the base dropped), or None if outside."""
    pb = _plain(base)
    # walk the term path step by step until its predicate-less prefix equals the base
    steps = re.split(r"/(?![^\[]*\])", term)
    for i in range(1, len(steps) + 1):
        head = "/".join(steps[:i])
        if _plain(head) == pb:
            rest = "/".join(steps[i:])
            # keep the base's own predicate on its last step if the term repeats it
            return rest or "."
    return None


def _date(text: str) -> str:
    if re.fullmatch(r"\d{8}", text):
        try:
            return dt.datetime.strptime(text, "%Y%m%d").date().isoformat()
        except ValueError:
            return text
    return text


def _value(bt: str, node, tree, datatype: str | None) -> Value | None:
    if isinstance(node, etree._Element):
        text, el, attr = (node.text or "").strip(), node, None
    else:
        text, el, attr = str(node).strip(), node.getparent(), node.attrname
    if not text or el is None:
        return None
    path = tree.getpath(el) + (f"/@{attr}" if attr else "")
    nice = re.sub(r"\b(rsm|ram|udt|qdt):", "", path)
    nice = re.sub(r"\[1\]", "", nice)
    raw = None
    if datatype == "Date" or (isinstance(node, etree._Element) and etree.QName(node).localname in ("DateTimeString", "DateString")):
        iso = _date(text)
        raw, text = (text, iso) if iso != text else (None, text)
    return Value(bt, text, line=el.sourceline, segment=nice, raw=raw,
                 scheme=el.get("schemeID") if attr is None else None, rule=path)


def _label(bg: str, el, n: int, ns) -> str:
    if bg == "BG-25":
        return f"řádek {el.findtext('ram:AssociatedDocumentLineDocument/ram:LineID', namespaces=ns) or n}"
    if bg == "BG-23":
        return f"DPH {el.findtext('ram:RateApplicablePercent', namespaces=ns) or '?'} % {el.findtext('ram:CategoryCode', namespaces=ns) or ''}".strip()
    return {"BG-20": "sleva dokladu", "BG-21": "přirážka dokladu", "BG-27": "sleva", "BG-28": "přirážka"}[bg] + f" #{n}"


def read(data: bytes) -> Semantic:
    root = etree.fromstring(data, etree.XMLParser(resolve_entities=False, no_network=True))
    tree = root.getroottree()
    b = binding()
    ns = b["namespaces"]
    cat = catalog()

    repeating: dict[str, str] = {}
    for tid in cat.order:
        for anc in cat.ancestors(tid):
            if anc in REPEATING:
                repeating[tid] = anc
                break

    document = Context(None, "doklad", root.sourceline)
    groups: dict[str, list[Context]] = {}
    nodes: dict[str, list] = {}
    for bg in REPEATING:
        base = b["groups"][bg][0]
        nodes[bg] = root.xpath(base, namespaces=ns)
        groups[bg] = [Context(bg, _label(bg, el, n, ns), el.sourceline) for n, el in enumerate(nodes[bg], 1)]

    rules: dict[str, list[dict]] = {}
    for tid, paths in b["terms"].items():
        t = cat.get(tid)
        if t is None or t.kind != "BT":
            continue
        rules[tid] = [{"path": re.sub(r"\b(rsm|ram|udt|qdt):", "", p), "value": "text"} for p in paths]
        bg = repeating.get(tid)
        for p in paths:
            if bg is None:
                for node in root.xpath(p, namespaces=ns):
                    v = _value(tid, node, tree, t.datatype)
                    if v:
                        document.add(v)
                continue
            rel = _relative(p, b["groups"][bg][0])
            if rel is None:
                continue
            if bg == "BG-25":  # line allowances vs charges share one element – use the sub-group's discriminator
                for sub in LINE_SUB:
                    if sub in cat.ancestors(tid):
                        sub_rel = _relative(b["groups"][sub][0], b["groups"]["BG-25"][0])
                        rel = sub_rel + rel[len(_plain(sub_rel)):] if rel.startswith(_plain(sub_rel)) else rel
            for el, ctx in zip(nodes[bg], groups[bg]):
                for node in el.xpath(rel, namespaces=ns):
                    v = _value(tid, node, tree, t.datatype)
                    if v:
                        ctx.add(v)

    bt3 = document.values.get("BT-3")
    cn_codes = codelists().get("UNCL1001-cn", {}).get("codes", {})
    kind = "CreditNote" if bt3 and bt3[0].value in cn_codes else "Invoice"
    return Semantic(source_format="UN/CEFACT CII D16B", mapping_id="cii-en16931-syntax-binding", document=document,
                    groups=groups, mapped_terms=set(rules), rules=rules, repeating=repeating, doc_kind=kind)
