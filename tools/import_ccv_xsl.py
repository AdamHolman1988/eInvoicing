"""Generate msgvalidator/data/orion/ccv_xml_to_orion3.xsl from the production converter
"INVOIC exp ORION 3 XML" (CCV eBUS XML <INVOIC><HDR>… -> ORION XML 3).

    python tools/import_ccv_xsl.py "<OneDrive>\\Dokumenty\\Archiv\\Obecny INVOIC exp Orion 3 XML v17\\invoic.xsl"

The source is only read. Removed from the copy: the Oracle/Java extension functions and the ORION URL
block (it builds a download link with a login and password from the database) – the URL is always
'Not requested'.
"""
import pathlib
import sys

from lxml import etree

XSL = "http://www.w3.org/1999/XSL/Transform"
OUT = pathlib.Path(__file__).resolve().parents[1] / "msgvalidator" / "data" / "orion" / "ccv_xml_to_orion3.xsl"


def main(src: str):
    tree = etree.parse(src)
    root = tree.getroot()
    for p in root.findall(f"{{{XSL}}}param[@name='connection']"):
        root.remove(p)
    for v in root.iter(f"{{{XSL}}}variable"):
        if v.get("name") == "OrionURL":
            for c in list(v):
                v.remove(c)
            v.text = None
            etree.SubElement(v, f"{{{XSL}}}value-of", select="'Not requested'")
    for o in root.findall(f"{{{XSL}}}output"):
        o.set("encoding", "utf-8")  # production writes windows-1250; here the result stays in memory
    text = etree.tostring(tree, encoding="unicode")
    assert "db:" not in text and "datasource:" not in text.replace('xmlns:datasource', ''), "DB extension still used"
    root.set("exclude-result-prefixes", "edi xs")
    nsmap = {k: v for k, v in root.nsmap.items() if k not in ("db", "datasource")}
    new = etree.Element(root.tag, nsmap=nsmap, attrib=dict(root.attrib))
    new.text, new[:] = root.text, list(root)
    header = ("<!-- Generated by tools/import_ccv_xsl.py from the production converter 'INVOIC exp ORION 3 XML' "
              "(DB extensions and ORION URL removed). Do not edit by hand. -->\n")
    OUT.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + header
                   + etree.tostring(new, encoding="unicode"), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main(sys.argv[1])
