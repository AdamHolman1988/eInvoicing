"""Download, pin and prepare the official validation artefacts into msgvalidator/data/rules.

    python tools/update_rules.py [--cache DIR]

Layout produced (all paths relative to msgvalidator/data/rules):
    VERSIONS.json                       pinned versions + source URLs
    peppol/scenarios.xml                KoSIT scenario config (our own, see tools/templates) ...
    peppol/resources/ubl/xsd/...        UBL 2.1 XSD (Invoice, CreditNote + common)
    peppol/resources/cii/xsd/...        CII D16B XSD
    peppol/resources/cen/*.xslt         CEN EN 16931 (UBL, CII)
    peppol/resources/peppol/*.xslt      Peppol BIS 3 (UBL, CII) compiled from .sch with SchXslt2
    peppol/resources/sk/SK-CIUS-UBL.*   SK CIUS Schematron generated by tools/build_sk_schematron.py + compiled
    peppol/resources/default-report.xsl KoSIT default report (Apache-2.0)
    xrechnung/                          official KoSIT XRechnung configuration, unchanged
"""
from __future__ import annotations

import argparse
import io
import json
import pathlib
import shutil
import tempfile
import urllib.request
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
DST = ROOT / "msgvalidator" / "data" / "rules"
TEMPLATE = ROOT / "tools" / "templates" / "peppol-scenarios.xml"

VERSIONS = {
    "cen": {"version": "1.3.17",
            "ubl": "https://github.com/ConnectingEurope/eInvoicing-EN16931/releases/download/validation-1.3.17/en16931-ubl-1.3.17.zip",
            "cii": "https://github.com/ConnectingEurope/eInvoicing-EN16931/releases/download/validation-1.3.17/en16931-cii-1.3.17.zip"},
    "peppol": {"version": "3.0.21",
               "url": "https://github.com/OpenPEPPOL/peppol-bis-invoice-3/archive/refs/tags/3.0.21.zip"},
    "schxslt2": {"version": "1.11.3",
                 "url": "https://repo1.maven.org/maven2/name/dmaus/schxslt/schxslt2/1.11.3/schxslt2-1.11.3.jar"},
    "kosit-xrechnung": {"version": "v2026-08-31",
                        "url": "https://github.com/itplr-kosit/validator-configuration-xrechnung/releases/download/v2026-08-31/xrechnung-3.0.2-validator-configuration-2026-08-31.zip"},
}


def fetch(url: str, cache: pathlib.Path) -> zipfile.ZipFile:
    f = cache / url.rsplit("/", 1)[-1]
    if not f.exists():
        print("download", url)
        with urllib.request.urlopen(url, timeout=120) as r:
            f.write_bytes(r.read())
    return zipfile.ZipFile(f)


def extract(z: zipfile.ZipFile, member_suffix: str, dst: pathlib.Path) -> pathlib.Path:
    name = next(n for n in z.namelist() if n.endswith(member_suffix))
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(z.read(name))
    return dst


def compile_sch(sch: pathlib.Path, out: pathlib.Path, transpile: pathlib.Path) -> None:
    from saxonche import PySaxonProcessor
    with PySaxonProcessor(license=False) as proc:
        xp = proc.new_xslt30_processor()
        exe = xp.compile_stylesheet(stylesheet_file=str(transpile))
        exe.transform_to_file(source_file=str(sch), output_file=str(out))
    print("compiled", sch.name, "->", out.relative_to(DST), f"{out.stat().st_size // 1024} kB")


def main(cache: pathlib.Path) -> None:
    cache.mkdir(parents=True, exist_ok=True)
    if DST.exists():
        shutil.rmtree(DST)
    peppol_dir = DST / "peppol"
    res = peppol_dir / "resources"

    # XSDs + KoSIT default report from the official KoSIT configuration package
    kz = fetch(VERSIONS["kosit-xrechnung"]["url"], cache)
    for n in kz.namelist():
        if n.endswith("/"):
            continue
        if "/ubl/2.1/xsd/common/" in "/" + n or n.endswith(("UBL-Invoice-2.1.xsd", "UBL-CreditNote-2.1.xsd")):
            sub = n.split("xsd/", 1)[1]
            (res / "ubl" / "xsd" / sub).parent.mkdir(parents=True, exist_ok=True)
            (res / "ubl" / "xsd" / sub).write_bytes(kz.read(n))
        elif "/cii/16b/xsd/" in "/" + n:
            p = res / "cii" / "xsd" / n.rsplit("/", 1)[-1]
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(kz.read(n))
    extract(kz, "resources/default-report.xsl", res / "default-report.xsl")
    # the whole XRechnung configuration as a second, unmodified KoSIT repository
    xr = DST / "xrechnung"
    kz.extractall(xr)

    # CEN EN 16931
    extract(fetch(VERSIONS["cen"]["ubl"], cache), "xslt/EN16931-UBL-validation.xslt", res / "cen" / "EN16931-UBL-validation.xslt")
    extract(fetch(VERSIONS["cen"]["cii"], cache), "xslt/EN16931-CII-validation.xslt", res / "cen" / "EN16931-CII-validation.xslt")

    # Peppol BIS 3: compile official Schematron with SchXslt2
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        sz = fetch(VERSIONS["schxslt2"]["url"], cache)
        sz.extractall(tmp / "schxslt2")
        transpile = next((tmp / "schxslt2").rglob("transpile.xsl"))
        pz = fetch(VERSIONS["peppol"]["url"], cache)
        for flavour in ("UBL", "CII"):
            sch = extract(pz, f"rules/sch/PEPPOL-EN16931-{flavour}.sch", tmp / f"PEPPOL-EN16931-{flavour}.sch")
            compile_sch(sch, res / "peppol" / f"PEPPOL-EN16931-{flavour}.xslt", transpile)
        # SK CIUS: our own Schematron generated from the SK profile, compiled the same way
        import build_sk_schematron
        build_sk_schematron.build(res / "sk", transpile)
        # Peppol example documents for tests
        ex = ROOT / "tests" / "samples" / "ubl"
        ex.mkdir(parents=True, exist_ok=True)
        for n in ("rules/examples/base-example.xml", "rules/examples/base-creditnote-correction.xml"):
            extract(pz, n, ex / ("peppol_" + n.rsplit("/", 1)[-1]))

    shutil.copy(TEMPLATE, peppol_dir / "scenarios.xml")
    (DST / "VERSIONS.json").write_text(json.dumps(VERSIONS, indent=1), encoding="utf-8")
    size = sum(p.stat().st_size for p in DST.rglob("*") if p.is_file())
    print(f"done – {size / 1e6:.1f} MB in {DST}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=str(pathlib.Path(tempfile.gettempdir()) / "msgvalidator-rules-cache"))
    main(pathlib.Path(ap.parse_args().cache))
