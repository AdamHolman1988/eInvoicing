"""Collect Czech UI / message texts into msgvalidator/data/i18n/en.yaml (Czech -> English phrase table).

    python tools/i18n_extract.py          # adds new phrases with an empty translation, keeps existing ones

Sources: string literals in msgvalidator/**/*.py (f-strings split at {placeholders}), the HTML/JS page templates,
and human-readable values in data files (IDoc dictionary, mapping notes, profile descriptions).
Translation at runtime: msgvalidator/i18n.py (longest phrase first, whole words only).
"""
import ast
import json
import pathlib
import re

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1] / "msgvalidator"
OUT = ROOT / "data" / "i18n" / "en.yaml"
CZ = re.compile(r"[ěščřžýáíéůúňťďĚŠČŘŽÝÁÍÉŮÚŇŤĎ]")
# Czech words without diacritics that appear on their own in the UI
ASCII_CZ = re.compile(r"\b(chyb|chyba|chyby|doklad|dokladu|Hotovo|info|Kde|Kod|pravidla|prazdne|Profily|varovani)\b")
TEMPLATE_RUN = re.compile(r"[^<>\"'`{}$=;()\[\]|\\\r\n]+")  # text runs; keep() decides what is Czech


# Czech words without diacritics – a text containing one of them is Czech even without háčky/čárky
CZ_WORDS = re.compile(r"(?<![\w-])(se|ze|na|pro|jen|nebo|je|ve|od|pole|hledat|vzorek|vzorku|klient|klienta|Porovnat|profily|"
                      r"Standardy|Znovu|zkontrolovat|Odkud|bere|doklad|dokladu|Druh|faktura|dobropis|pravidla|skupinu|neplnit|"
                      r"neobsahuje|Soubor|soubor|Kontrola|kontrola|hodnot|Hodnota|hodnota|Stav|Popis|Struktura|Zobrazit|Hotovo|Bez|"
                      r"chyb|Profily|Mena|Nazev|Ulice|Mesto|Telefon|Jazyk|Banka|Kurz|Hmotnost|Okres|Divize|"
                      r"Sazba|Typ|Znak|Kvalifikator|Identifikator|partnera|Podminky|Zaklad|Castka|Cena|Mnozstvi|"
                      r"jednotka|Jednotka|Stav|Smer|Klient|Organizace|Skupina|Vase|Rozsireni|Verze|Cislo)(?![\w-])")
SKIP = re.compile(r"A-Z|^[\w./\-]+$|^https?:")


def keep(s: str, data: bool = False) -> bool:
    s = s.strip()
    if not s or len(s) >= 600 or SKIP.search(s):
        return False
    if CZ.search(s) or CZ_WORDS.search(s):
        return True
    return data and " " in s and bool(re.search(r"[a-z]", s))  # labels in data files are Czech by definition


def from_python(path: pathlib.Path, out: set):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    docstrings = {id(n.value) for n in ast.walk(tree) if isinstance(n, ast.Expr) and isinstance(n.value, ast.Constant)}
    for node in ast.walk(tree):
        if id(node) in docstrings:
            continue
        if isinstance(node, ast.JoinedStr):
            for v in node.values:
                if isinstance(v, ast.Constant) and isinstance(v.value, str):
                    for part in re.split(r"\n", v.value):
                        if keep(part):
                            out.add(part.strip())
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            s = node.value
            if len(s) > 2000:  # page template -> text runs
                for m in TEMPLATE_RUN.finditer(s):
                    if keep(m.group(0)):
                        out.add(m.group(0).strip())
            else:
                for part in s.split("\n"):
                    if keep(part):
                        out.add(part.strip())


def from_data(out: set):
    d = ROOT / "data"
    for p in list((d / "idoc").glob("*.yaml")) + list((d / "mappings").glob("*.yaml")):
        def walk(x):
            if isinstance(x, dict):
                for v in x.values():
                    walk(v)
            elif isinstance(x, list):
                for v in x:
                    walk(v)
            elif isinstance(x, str) and keep(x, data=True):
                out.add(x.strip())
        walk(yaml.safe_load(p.read_text(encoding="utf-8")))
    for p in (d / "profiles").glob("*.json"):
        raw = json.loads(p.read_text(encoding="utf-8"))
        for k in ("name", "description"):
            if keep(raw.get(k, "")):
                out.add(raw[k].strip())


def main():
    found: set[str] = set()
    for p in ROOT.rglob("*.py"):
        if "__pycache__" not in p.parts and p.name != "docs_page.py":  # docs are written in both languages
            from_python(p, found)
    from_data(found)
    old = yaml.safe_load(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    old = old or {}
    merged = {k: old.get(k, "") for k in sorted(found)}
    for k, v in old.items():  # keep translated manual entries that are no longer found verbatim
        if v:
            merged.setdefault(k, v)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("# Czech -> English phrase table. Generated by tools/i18n_extract.py, translations are manual.\n"
                   + yaml.safe_dump(merged, allow_unicode=True, sort_keys=True, width=200), encoding="utf-8")
    print(f"{OUT}: {len(merged)} phrases, {sum(1 for v in merged.values() if not v)} untranslated")


if __name__ == "__main__":
    main()
